

// ! Primitive Datatypes in Typescript 


// 1. string 

let myName : string = "santanu";
let myCity : string = 'chennai';
let aboutMe : string = `I am a fullstack MERN Developer.`;

console.log(typeof myName);

// 2. number 

let myId : number = 101 ;
let myHeight : number = 5.7 ;

console.log(typeof myHeight)


// 3. boolean 

let isStudent : boolean = true

console.log(typeof isStudent)

// 4. undefined 

let salary : undefined = undefined ; 

console.log(typeof salary)

// 5. null 

let empty : null = null;
console.log(typeof empty)  

// 6. bigInt 

let hugeNumber : bigint = 987654321234567n

console.log(typeof hugeNumber)

