"use strict";
// ! Primitive Datatypes in Typescript 
// 1. string 
let myName = "santanu";
let myCity = 'chennai';
let aboutMe = `I am a fullstack MERN Developer.`;
console.log(typeof myName);
// 2. number 
let myId = 101;
let myHeight = 5.7;
console.log(typeof myHeight);
// 3. boolean 
let isStudent = true;
console.log(typeof isStudent);
// 4. undefined 
let salary = undefined;
console.log(typeof salary);
// 5. null 
let empty = null;
console.log(typeof empty);
// 6. bigInt 
let hugeNumber = 987654321234567n;
console.log(typeof hugeNumber);
